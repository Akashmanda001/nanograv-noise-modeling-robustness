import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

from config import OUTPUT_DIR


def hellings_downs(theta_deg):

    x = (
        1
        - np.cos(np.radians(theta_deg))
    ) / 2

    return (
        0.5
        - x / 4
        + 1.5 * x * np.log(x)
    )


