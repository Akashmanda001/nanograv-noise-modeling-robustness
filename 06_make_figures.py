def figure_3():

    df = pd.read_csv(
        OUTPUT_DIR / "selection_group_correlations.csv"
    )

    groups = [
        "Strong",
        "Moderate",
        "Weak",
    ]

    original = [
        df.loc[
            df["group"] == g,
            "original_correlation",
        ].values
        for g in groups
    ]

    whitened = [
        df.loc[
            df["group"] == g,
            "white_correlation",
        ].values
        for g in groups
    ]

    fig, ax = plt.subplots(
        figsize=(10, 6)
    )

    original_positions = [
        1, 4, 7
    ]

    whitened_positions = [
        2, 5, 8
    ]

    ax.boxplot(
        original,
        positions=original_positions,
        widths=0.6,
    )

    ax.boxplot(
        whitened,
        positions=whitened_positions,
        widths=0.6,
    )

    ax.axhline(
        0,
        linewidth=0.8,
    )

    ax.set_xticks(
        [1.5, 4.5, 7.5]
    )

    ax.set_xticklabels(groups)

    ax.set_xlabel(
        "Pulsar-selection group"
    )

    ax.set_ylabel(
        "Pairwise Pearson correlation"
    )

    ax.set_title(
        "Pairwise Correlations Before and "
        "After Whitening"
    )

    ax.grid(
        axis="y",
        alpha=0.25,
    )

    # Add simple labels above each pair.
    ax.text(
        1.0,
        ax.get_ylim()[1] * 0.95,
        "Original",
        ha="center",
    )

    ax.text(
        2.0,
        ax.get_ylim()[1] * 0.95,
        "Whitened",
        ha="center",
    )

    plt.tight_layout()

    plt.savefig(
        OUTPUT_DIR
        / "Figure3_correlation_distributions.png",
        dpi=200,
    )

    plt.close()


