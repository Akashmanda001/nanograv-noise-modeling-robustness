def figure_4():

    df = pd.read_csv(
        OUTPUT_DIR / "selection_group_correlations.csv"
    )

    rows = []

    for group in [
        "Strong",
        "Moderate",
        "Weak",
    ]:

        d = df[df["group"] == group]

        original_std = (
            d["original_correlation"].std()
        )

        whitened_std = (
            d["white_correlation"].std()
        )

        reduction = (
            100
            * (1 - whitened_std / original_std)
        )

        rows.append(
            {
                "group": group,
                "reduction": reduction,
            }
        )

    stats = pd.DataFrame(rows)

    plt.figure(figsize=(8, 6))

    plt.bar(
        stats["group"],
        stats["reduction"],
    )

    plt.ylabel(
        "Reduction in correlation scatter (%)"
    )

    plt.xlabel(
        "Pulsar-selection group"
    )

    plt.title(
        "Reduction in Pairwise Correlation Scatter "
        "Following Whitening"
    )

    plt.ylim(0, 100)

    plt.grid(
        axis="y",
        alpha=0.25,
    )

    plt.tight_layout()

    plt.savefig(
        OUTPUT_DIR / "Figure4_scatter_reduction.png",
        dpi=200,
    )

    plt.close()


