def figure_6():

    df = pd.read_csv(
        OUTPUT_DIR / "ten_pulsar_pair_correlations.csv"
    )

    bins = np.arange(
        0,
        181,
        20,
    )

    df["bin"] = pd.cut(
        df["separation_deg"],
        bins=bins,
        include_lowest=True,
    )

    grouped = (
        df.groupby(
            "bin",
            observed=True,
        )["white_correlation"]
        .agg(
            ["mean", "std", "count"]
        )
    )

    midpoints = np.array(
        [
            interval.mid
            for interval in grouped.index
        ]
    )

    error = (
        grouped["std"]
        / np.sqrt(grouped["count"])
    )

    theta = np.linspace(
        0.01,
        180,
        500,
    )

    hd = hellings_downs(theta)

    plt.figure(figsize=(10, 6))

    plt.plot(
        theta,
        hd,
        linewidth=2,
        label="Hellings–Downs curve",
    )

    plt.errorbar(
        midpoints,
        grouped["mean"],
        yerr=error,
        fmt="o",
        markersize=7,
        capsize=4,
        label="Whitened correlations",
    )

    for x, y, n in zip(
        midpoints,
        grouped["mean"],
        grouped["count"],
    ):

        plt.annotate(
            f"N={int(n)}",
            (x, y),
            xytext=(0, 10),
            textcoords="offset points",
            ha="center",
            fontsize=9,
        )

    plt.axhline(
        0,
        linewidth=0.8,
    )

    plt.xlabel(
        "Pulsar angular separation (degrees)"
    )

    plt.ylabel(
        "Mean whitened Pearson correlation"
    )

    plt.title(
        "Mean Whitened Pairwise Correlation "
        "in 20° Angular-Separation Bins"
    )

    plt.xlim(0, 180)

    plt.grid(alpha=0.25)

    plt.legend()

    plt.tight_layout()

    plt.savefig(
        OUTPUT_DIR
        / "Figure6_binned_correlations.png",
        dpi=200,
    )

    plt.close()


